// Move assignment operator
Spreadsheet& Spreadsheet::operator=(Spreadsheet&& rhs) noexcept
{

    std::println("Move assignment operator: from ({}, {}) to ({}, {})",
        rhs.width_, rhs.height_, width_, height_);

    // // Check for self-assignment: Recommended by C++ Core Guidelines
    // if (this == &rhs) return *this;

    // // Free the old memory and move ownership
    // cleanup();
    // moveFrom(rhs);

    // Using "move-and-swap idiom" (See copy-and-swap idiom)

    auto moved { std::move(rhs) };  // move `rhs` into `moved` (noexcept)
    swap(moved);                    // Commit the work with only non-throwing operations

    // As the function returns, `moved` gets out of scope, and its destructor is called

    return *this;
}
bool Spreadsheet::inRange(std::size_t value, std::size_t upper) const
{
    return value < upper;
}

void Spreadsheet::verifyCoordinate(std::size_t x, std::size_t y) const
{
    if (! inRange(x, width_))
    {
        throw std::out_of_range {
            std::format("x ({}) must be less than width ({}).", x, width_)
        };
    }

    if (! inRange(y, height_))
    {
        throw std::out_of_range {
            std::format("y ({}) must be less than height ({}).", y, height_)
        };
    }
}

void Spreadsheet::setCellAt(std::size_t x, std::size_t y, const SpreadsheetCell& cell)
{
    verifyCoordinate(x, y);
    cells_[x][y] = cell;
}

SpreadsheetCell& Spreadsheet::getCellAt(std::size_t x, std::size_t y)
{
    verifyCoordinate(x, y);
    return cells_[x][y];
}


